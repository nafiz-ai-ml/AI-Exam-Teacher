/**
 * Builds the user prompt incorporating all educational metadata and page ordering.
 */
export function buildEvaluationUserPrompt(params: {
  classLevel: string;
  subject: string;
  chapter?: string;
  totalMarks: number;
  questionText?: string;
  stimulusText?: string;
  sourceText?: string;
  partsConfig: { part: string; max_score: number }[];
  questionImagesCount: number;
  stimulusImagesCount: number;
  sourceImagesCount: number;
  answerImagesCount: number;
}): string {
  const partsDescription = params.partsConfig
    .map((p) => `- অংশ: '${p.part}' (বরাদ্দকৃত পূর্ণমান: ${p.max_score})`)
    .join('\n');

  return `অনুগ্রহ করে নিচের তথ্যের ভিত্তিতে সৃজনশীল (CQ) পরীক্ষার উত্তরটি মূল্যায়ন করুন:

[প্রাতিষ্ঠানিক তথ্য]:
- শ্রেণি: ${params.classLevel}
- বিষয়: ${params.subject}
${params.chapter ? `- অধ্যায়: ${params.chapter}` : ''}
- পরীক্ষার মোট পূর্ণমান: ${params.totalMarks}

[প্রশ্নের অংশসমূহ ও নম্বর বণ্টন]:
${partsDescription}

${params.questionText ? `[প্রশ্নের পূর্ণাঙ্গ টেক্সট]:\n"""\n${params.questionText}\n"""\n` : ''}
${params.stimulusText ? `[উদ্দীপক / প্রাসঙ্গিক উদ্দীপক অংশ]:\n"""\n${params.stimulusText}\n"""\n` : ''}
${params.sourceText ? `[শিক্ষক প্রদত্ত পাঠ্যবইয়ের রেফারেন্স / সূত্র]:\n"""\n${params.sourceText}\n"""\n` : ''}

[সংযুক্ত ভিজ্যুয়াল নথিপত্র]:
- প্রশ্নপত্রের ছবি: ${params.questionImagesCount > 0 ? `${params.questionImagesCount}টি পাতা সংযুক্ত` : 'দেওয়া হয়নি (টেক্সট দ্রষ্টব্য)'}
- উদ্দীপকের ছবি: ${params.stimulusImagesCount > 0 ? `${params.stimulusImagesCount}টি পাতা সংযুক্ত` : 'দেওয়া হয়নি'}
- পাঠ্যবই রেফারেন্সের ছবি: ${params.sourceImagesCount > 0 ? `${params.sourceImagesCount}টি পাতা সংযুক্ত` : 'দেওয়া হয়নি'}
- শিক্ষার্থীর হস্তলিখিত খাতার পাতা: ${params.answerImagesCount > 0 ? `${params.answerImagesCount}টি পাতা ক্রমানুসারে (পৃষ্ঠা ১, পৃষ্ঠা ২...) সংযুক্ত` : 'দেওয়া হয়নি'}

[মূল্যায়ন নির্দেশনা]:
১. প্রথমে প্রতিটি অংশের "প্রশ্নের চাহিদা" চিহ্নিত করুন।
২. শিক্ষার্থীর উত্তর নিজের ভাষায় লিখিত হলেও ধারণাগত সঠিকতা থাকলে প্রাপ্য যথাযথ নম্বর দিন। মুখস্থ শব্দ না হওয়ার কারণে নম্বর কাটবেন না।
৩. শুধুমাত্র ভ্যালিড JSON অবজেক্ট আউটপুট দিন।`;
}
